    konsept = tmp_path / "01_Konsept_ve_ArGe"
    konsept.mkdir(parents=True)
    sku_dir = urunler / "yeni-saksi"
    (sku_dir / "model").mkdir(parents=True)
    stl = sku_dir / "model" / "yeni-saksi.stl"
    stl.write_bytes(b"solid s")

    monkeypatch.setattr(me, "URUNLER_KLASORU", urunler)
    me.urun_yaml_kalite_guncelle("yeni-saksi", stl, {"durum": "RED", "boyut_mm": {"x": 120.0, "y": 120.0, "z": 135.0}, "hacim_cm3": 250.0, "tahmini_pla_gram": 95.0})
    red_yaml = yaml.safe_load((sku_dir / "urun.yaml").read_text(encoding="utf-8"))
    assert red_yaml["durum"] == "REVIZE"
    assert red_yaml["boyut_mm"] == {"x": 120.0, "y": 120.0, "z": 135.0}

