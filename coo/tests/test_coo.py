def test_claude_akis_buyuk_init_ve_oturum_kaydi(tmp_path: Path, monkeypatch) -> None:
    import sys
    import coo.__main__ as cm

    sahte_cli = tmp_path / "claude"
    # 160 KB boyutunda system:init + tool_use + result üreten sahte Claude CLI betiği
    sahte_cli.write_text(
        f"#!{sys.executable}\n"
        "import json, sys, time\n"
        "init = {'type': 'system', 'subtype': 'init', 'session_id': 'sess-test-1234', 'pad': 'x' * 160000}\n"
        "print(json.dumps(init), flush=True)\n"
        "asst = {'type': 'assistant', 'session_id': 'sess-test-1234', 'message': {'content': [{'type': 'tool_use', 'name': 'Bash', 'input': {'command': 'echo ok'}}]}}\n"
        "print(json.dumps(asst), flush=True)\n"
        "res = {'type': 'result', 'session_id': 'sess-test-1234', 'is_error': False, 'num_turns': 1, 'result': 'TAMAM'}\n"
        "print(json.dumps(res), flush=True)\n",
        encoding="utf-8",
    )
    sahte_cli.chmod(0o755)

    monkeypatch.setattr(cm, "_claude_ikili_yolu", lambda: str(sahte_cli))
    monkeypatch.setattr(cm, "CALISMA_ALANI", tmp_path)
    monkeypatch.setattr(cm, "OTURUM_DOSYASI", tmp_path / "oturumlar.json")
    cm.BELLEK.devam_oturumlari.clear()
    cm.BELLEK.son_oturum_anahtari = ""

    kayit: dict = {}
    ok, yanit, sid = asyncio.run(
        cm.claude_ajan_akisi_calistir("ceo", "Test istemi", zaman_asimi=0, gorev_kaydi=kayit)
    )
    assert ok is True
    assert yanit == "TAMAM"
    assert sid == "sess-test-1234"
    assert kayit["arac_sayisi"] == 1
    assert "Bash" in kayit["son_arac"]

    anahtar = cm._oturum_kaydet(sid, "ceo-orchestrator", "Test ozeti")
    assert anahtar is not None
    bulunan = cm._oturum_al(anahtar)
    assert bulunan is not None and bulunan[1]["session_id"] == "sess-test-1234"


